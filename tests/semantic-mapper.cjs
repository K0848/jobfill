// 语义映射只做精确归一化；新增标签必须绑定到明确资料键，不猜测模糊近义词。
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const sandbox = { console };
sandbox.globalThis = sandbox;
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../extension/semantic-mapper.js'), 'utf8'), sandbox);
const mapper = sandbox.JobfillSemanticMapper;
assert.equal(mapper.version, 5);
assert(mapper.optionMatches('degree','硕士','硕士（Master）'));
assert(mapper.optionMatches('degree','本科（Bachelor）','本科'));
assert(!mapper.optionMatches('degree','硕士','硕士（非全日制）'));
assert(!mapper.optionMatches('role','硕士','硕士（Master）'));
assert.equal(mapper.resolve('所在院系/研究所'), 'college');
assert.equal(mapper.resolve('学校所在地'), 'studyLocation');
assert.equal(mapper.resolve('目前就读地'), null, '学校所在地不能借用个人当前城市');
assert.equal(mapper.resolve('学位'), 'academicDegree');
assert.equal(mapper.resolve('学历'), 'degree');
assert.equal(mapper.resolve('身高(厘米)'), 'heightCm');
assert.equal(mapper.resolve('体重(公斤)'), 'weightKg');
assert.equal(mapper.resolve('身高(英寸)'), null, '不得把英制单位误复用为厘米');
assert.equal(mapper.resolve('体重'), null, '无单位体重不得猜测公斤');
assert.equal(mapper.resolve('工作职责'), 'responsibilities', '限字职责优先使用已确认职责源，不读取整段工作描述');
assert.equal(mapper.resolve('工作描述'), 'description', '职责摘要不能覆盖完整描述的语义');
assert(mapper.optionMatches('degree', '硕士', '硕士研究生'));
assert(!mapper.optionMatches('academicDegree', '本科', '学士'), '不得从学历推断已获学位');
assert(!mapper.optionMatches('degree', '硕士', '非全日制硕士研究生'), '不能删去修读形式限定');
assert.equal(mapper.resolve('受教育类型'), 'studyForm');
assert.equal(mapper.resolve('学历类型'), 'studyForm', '学历类型下拉应映射为学习形式，不得误当学历层次');
assert.equal(mapper.resolve('英语等级', { adapter: 'generic' }), 'exam');
assert.equal(mapper.resolve('英语等级成绩', { adapter: 'generic' }), 'score');
assert.equal(mapper.resolve('英语等级', { adapter: 'moka' }), null, '其他站点不泛化英语等级字段');
assert.equal(mapper.resolve('  电子邮件 ', {}), 'email');
assert.equal(mapper.resolve('二级学院全称', { adapter: 'feishu' }), 'college');
assert.equal(mapper.resolve('二级学院全称', { adapter: 'generic' }), null);
assert.equal(mapper.resolve('描述', { adapter: 'tencent' }), 'description');
assert.equal(mapper.resolve('描述', { adapter: 'generic' }), null);
mapper.register({ labels: ['常用工具'], sourceKey: 'hobby', adapters: 'generic' });
assert.equal(mapper.resolve('常用工具', { adapter: 'generic' }), 'hobby');
assert.equal(mapper.resolve('常用工具', { adapter: 'moka' }), null);
assert.throws(() => mapper.register({ labels: ['常用工具'], sourceKey: 'email', adapters: 'generic' }), /语义标签存在冲突/);
console.log('semantic-mapper: ok');
